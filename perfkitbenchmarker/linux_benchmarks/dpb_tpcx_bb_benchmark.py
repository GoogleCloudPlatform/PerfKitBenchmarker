_SCALE_FACTOR = flags.DEFINE_integer(
    'dpb_tpcx_bb_scale_factor',
    100,
    'TPCx-BB scale factor (roughly GB of generated data). Must be one of '
    f'{tpcx_bb.VALID_SCALE_FACTORS} for a compliant run.',
    lower_bound=1,
)
_STREAMS = flags.DEFINE_integer(
    'dpb_tpcx_bb_streams',
    2,
    'Number of concurrent query streams in the throughput test.',
    lower_bound=1,
)
_ITERATIONS = flags.DEFINE_integer(
    'dpb_tpcx_bb_iterations',
    2,
    'Number of consecutive benchmark runs (data generation, load, power and '
    'throughput test each). The specification requires 2; the lower BBQpm is '
    'the reported one.',
    lower_bound=1,
)
_MAP_TASKS = flags.DEFINE_integer(
    'dpb_tpcx_bb_map_tasks',
    None,
    'Number of data generation map tasks (the kit driver -m option). '
    'Defaults to the total vCPUs of the workers.',
    lower_bound=1,
)
_RUN_TIMEOUT = flags.DEFINE_integer(
    'dpb_tpcx_bb_run_timeout',
    12 * 3600,
    'Seconds after which a benchmark run (one kit driver invocation) is '
    'killed. Raise it for scale factors above a few hundred.',
    lower_bound=600,
)
_SPARK_PROPERTIES = flags.DEFINE_list(
    'dpb_tpcx_bb_spark_properties',
    [],
    'Comma separated key=value Spark properties overriding the computed '
    'spark-defaults.conf of the spark-sql runs, e.g. '
    'spark.sql.shuffle.partitions=200.',
)
flags.register_validator(
    'dpb_tpcx_bb_spark_properties',
    lambda props: all(p.partition('=')[0].strip() and '=' in p for p in props),
    message='Each value must have the form key=value.',
)

FLAGS = flags.FLAGS

SUPPORTED_DPB_BACKENDS = (dpb_constants.UNMANAGED_DPB_SVC_YARN_CLUSTER,)
SUPPORTED_JAVA_VERSIONS = (8,)

# Margin between the driver's own timeout and the SSH command's.
_TIMEOUT_MARGIN_SECONDS = 600

# Reasons why a run is not compliant with the TPCx-BB specification.
REASON_KIT_MODIFIED = 'kit_modified_ml_jar_spark_3.1'
REASON_NO_ENGINE_VALIDATION = 'engine_validation_not_run'
REASON_SCALE_FACTOR = 'scale_factor_not_in_spec'
REASON_ITERATIONS = 'fewer_than_2_iterations'
REASON_REPLICATION = 'hdfs_replication_below_3'
REASON_INVALID_RESULT = 'invalid_result'


def GetConfig(user_config):
  return configs.LoadConfig(BENCHMARK_CONFIG, user_config, BENCHMARK_NAME)


def CheckPrerequisites(benchmark_config):
  """Verifies that the required resources and flags are present.

  Args:
    benchmark_config: Config needed to run the TPCx-BB benchmark.

  Raises:
    perfkitbenchmarker.errors.Config.InvalidValue: On encountering invalid
    configuration.
  """
  dpb_service_type = benchmark_config.dpb_service.service_type
  if dpb_service_type not in SUPPORTED_DPB_BACKENDS:
    raise errors.Config.InvalidValue(
        f'Invalid backend {dpb_service_type} for TPCx-BB. Not in: '
        f'{SUPPORTED_DPB_BACKENDS}'
    )
  if openjdk.OPENJDK_VERSION.value not in SUPPORTED_JAVA_VERSIONS:
    raise errors.Config.InvalidValue(
        'TPCx-BB needs Java 8 (the kit data generator uses JAXB, removed in '
        'Java 11, and Spark 3.1 does not run on Java 17+); pass '
        f'--openjdk_version=8 (got {openjdk.OPENJDK_VERSION.value}).'
    )
  if FLAGS.os_type not in os_types.DEBIAN_OS_TYPES:
    raise errors.Config.InvalidValue(
        'TPCx-BB only supports Debian based images (the metastore is '
        f'installed with apt); got --os_type={FLAGS.os_type}.'
    )
  if _SCALE_FACTOR.value not in tpcx_bb.VALID_SCALE_FACTORS:
    logging.warning(
        'TPCx-BB scale factor %d is not one of %s; results are not compliant.',
        _SCALE_FACTOR.value,
        tpcx_bb.VALID_SCALE_FACTORS,
    )


def GetSparkPropertyOverrides() -> dict[str, str]:
  """Returns --dpb_tpcx_bb_spark_properties as a dict."""
  overrides = {}
  for prop in _SPARK_PROPERTIES.value:
    key, _, value = prop.partition('=')
    overrides[key.strip()] = value.strip()
  return overrides


def GetNoncomplianceReasons(all_valid: bool) -> list[str]:
  """Returns why the run does not follow the TPCx-BB specification.

  Args:
    all_valid: Whether the kit declared every run VALID.

  Returns:
    Reason identifiers; empty for a compliant run. The kit modification and
    the missing engine validation run make this non-empty today.
  """
  reasons = [REASON_KIT_MODIFIED, REASON_NO_ENGINE_VALIDATION]
  if _SCALE_FACTOR.value not in tpcx_bb.VALID_SCALE_FACTORS:
    reasons.append(REASON_SCALE_FACTOR)
  if _ITERATIONS.value < 2:
    reasons.append(REASON_ITERATIONS)
  # Unset means the Hadoop default of 3, the minimum for the kit's data
  # redundancy requirement.
  replication = FLAGS.hadoop_hdfs_replication
  if replication is not None and replication < 3:
    reasons.append(REASON_REPLICATION)
  if not all_valid:
    reasons.append(REASON_INVALID_RESULT)
  return reasons


def _GetWorkers(service) -> list[Any]:
  workers = service.vms.get('worker_group') or []
  if not workers:
    raise errors.Benchmarks.PrepareException('No worker VMs in the cluster.')
  return workers


def _GetLeader(service):
  if service.leader is None:
    raise errors.Benchmarks.PrepareException(
        'Cannot set up TPCx-BB: leader VM is not initialized.'
    )
  return service.leader


def GetMapTasks(workers) -> int:
  if _MAP_TASKS.value:
    return _MAP_TASKS.value
  return sum(vm.NumCpusForBenchmark() for vm in workers)


def Prepare(benchmark_spec):
  """Sets up Spark on YARN, the metastore and the TPCx-BB kit.

  Args:
    benchmark_spec: The benchmark specification.

  Raises:
    errors.Benchmarks.PrepareException: If the cluster is not initialized.
  """
  service = benchmark_spec.dpb_service
  leader = _GetLeader(service)
  workers = _GetWorkers(service)
  background_tasks.RunThreaded(tpcx_bb.InstallSpark, [leader] + workers)
  tpcx_bb.ConfigureYarn(leader, workers)
  tpcx_bb.InstallMetastore(leader)
  worker = workers[0]
  spark_properties = tpcx_bb.GetSparkProperties(
      leader_ip=leader.internal_ip,
      worker_vcpus=worker.NumCpusForBenchmark(),
      worker_yarn_memory_mb=int(
          worker.total_memory_kb / 1024 * hadoop.YARN_MEMORY_FRACTION
      ),
      num_workers=len(workers),
      leader_memory_mb=int(leader.total_memory_kb / 1024),
      num_streams=_STREAMS.value,
      overrides=GetSparkPropertyOverrides(),
  )
  tpcx_bb.ConfigureSpark(leader, spark_properties)
  tpcx_bb.SmokeTestSpark(leader)
  leader.Install(tpcx_bb.PACKAGE_NAME)
  kit_dir = tpcx_bb.GetKitDir(leader)
  tpcx_bb.ConfigureKit(leader, kit_dir)
  benchmark_spec.tpcx_bb_kit_dir = kit_dir
  benchmark_spec.tpcx_bb_spark_properties = spark_properties


def _GetMetadata(
    service, spark_properties: dict[str, str], map_tasks: int, total_vcpus: int
) -> dict[str, object]:
  """Returns the metadata attached to every sample of a run."""
  metadata = dict(service.GetResourceMetadata())
  metadata.update({
      'tpcx_bb_scale_factor': _SCALE_FACTOR.value,
      'tpcx_bb_streams': _STREAMS.value,
      'tpcx_bb_iterations': _ITERATIONS.value,
      'tpcx_bb_map_tasks': map_tasks,
      'tpcx_bb_total_worker_vcpus': total_vcpus,
      'tpcx_bb_engine': tpcx_bb.KIT_ENGINE,
      'tpcx_bb_kit_file': tpcx_bb.KIT_FILE,
      'tpcx_bb_kit_modified': True,
      'tpcx_bb_spark_version': tpcx_bb.SPARK_VERSION.value,
      'tpcx_bb_spark_properties': ','.join(
          f'{k}={v}' for k, v in sorted(spark_properties.items())
      ),
  })
  return metadata


def _SaveLocalCopy(file_name: str, content: str) -> None:
  with open(os.path.join(vm_util.GetTempDir(), file_name), 'w') as f:
    f.write(content)


def _SaveKitLogs(leader, kit_dir: str, iteration: int) -> None:
  """Copies the kit's per query and data generation logs to the run dir."""
  archive = f'{tpcx_bb.TPCX_BB_DIR}/tpcx_bb_kit_logs_{iteration}.tgz'
  try:
    leader.RemoteCommand(f'tar -czf {archive} -C {kit_dir} logs')
    leader.PullFile(vm_util.GetTempDir(), archive)
  except errors.VirtualMachine.RemoteCommandError as e:
    logging.warning('Could not save the TPCx-BB kit logs: %s', e)


def RunIteration(
    benchmark_spec, iteration: int, map_tasks: int
) -> tuple[
    tpcx_bb.BenchmarkResult, dict[str, float], list[tpcx_bb.QueryTime], float
]:
  """Runs the kit driver once and parses its results.

  Args:
    benchmark_spec: The benchmark spec; Prepare must have run.
    iteration: 1-based run number.
    map_tasks: Number of data generation map tasks.

  Returns:
    The kit's result block, the per phase times, the per query times and the
    driver's wall time in seconds.

  Raises:
    errors.Benchmarks.RunError: If the driver timed out or printed no result.
  """
  leader = benchmark_spec.dpb_service.leader
  kit_dir = benchmark_spec.tpcx_bb_kit_dir
  driver_log = f'{tpcx_bb.TPCX_BB_DIR}/driver_{iteration}.log'
  command = tpcx_bb.GetRunCommand(
      kit_dir=kit_dir,
      scale_factor=_SCALE_FACTOR.value,
      num_streams=_STREAMS.value,
      map_tasks=map_tasks,
      driver_log=driver_log,
      timeout_seconds=_RUN_TIMEOUT.value,
  )
  start = time.time()
  stdout, _ = leader.RobustRemoteCommand(
      command, timeout=_RUN_TIMEOUT.value + _TIMEOUT_MARGIN_SECONDS
  )
  wall_time = time.time() - start
  exit_code = tpcx_bb.ParseDriverExitCode(stdout)
  log, _ = leader.RemoteCommand(f'cat {driver_log}', ignore_failure=True)
  times_csv, _ = leader.RemoteCommand(
      f'cat {kit_dir}/logs/times.csv', ignore_failure=True
  )
  _SaveLocalCopy(f'tpcx_bb_driver_{iteration}.log', log)
  _SaveLocalCopy(f'tpcx_bb_times_{iteration}.csv', times_csv)
  _SaveKitLogs(leader, kit_dir, iteration)
  # Jobs submitted by a killed or failed driver keep running on YARN.
  tpcx_bb.KillYarnApplications(leader)
  logging.info(
      'TPCx-BB run %d: driver exit code %s, wall time %.1f s',
      iteration,
      exit_code,
      wall_time,
  )
  if exit_code in tpcx_bb.TIMEOUT_EXIT_CODES:
    raise errors.Benchmarks.RunError(
        f'TPCx-BB run {iteration} timed out after {_RUN_TIMEOUT.value} s '
        '(--dpb_tpcx_bb_run_timeout).'
    )
  result = tpcx_bb.ParseResult(log)
  if result is None:
    problems = tpcx_bb.ParseProblems(log)
    tail = '\n'.join(log.splitlines()[-20:])
    raise errors.Benchmarks.RunError(
        f'TPCx-BB run {iteration} produced no result (driver exit code '
        f'{exit_code}). Kit problems: {problems}. Last driver log lines:\n'
        f'{tail}'
    )
  if result.scale_factor != _SCALE_FACTOR.value:
    logging.warning(
        'Kit reported BBQpm@%d but scale factor %d was requested.',
        result.scale_factor,
        _SCALE_FACTOR.value,
    )
  computed = tpcx_bb.ComputeBbqpm(
      _SCALE_FACTOR.value, result.t_ld, result.t_pt, result.t_tt
  )
  if abs(computed - result.bbqpm) > 0.001 * max(result.bbqpm, 1e-9):
    logging.warning(
        'BBQpm reported by the kit (%s) differs from the one computed from '
        'its times (%s).',
        result.bbqpm,
        computed,
    )
  phase_times = tpcx_bb.ParsePhaseTimes(log)
  query_times = tpcx_bb.ParseTimesCsv(times_csv, _SCALE_FACTOR.value)
  return result, phase_times, query_times, wall_time


def Run(benchmark_spec) -> list[sample.Sample]:
  """Runs the configured number of TPCx-BB benchmark runs.

  Args:
    benchmark_spec: Spec needed to run the benchmark.

  Returns:
    Per run result, phase and query samples and the reported BBQpm.

  Raises:
    errors.Benchmarks.RunError: If a run times out or produces no result.
  """
  service = benchmark_spec.dpb_service
  workers = _GetWorkers(service)
  map_tasks = GetMapTasks(workers)
  total_vcpus = sum(vm.NumCpusForBenchmark() for vm in workers)
  metadata = _GetMetadata(
      service, benchmark_spec.tpcx_bb_spark_properties, map_tasks, total_vcpus
  )

  # (metric, value, unit, extra metadata); samples are built at the end once
  # the validity of all runs is known.
  raw_samples = []
  if service.resource_ready_time and service.create_start_time:
    create_time = service.GetClusterCreateTime()
    if create_time is not None:
      raw_samples.append(('Time to Create', create_time, 'seconds', {}))

  bbqpms = []
  validity = []
  for iteration in range(1, _ITERATIONS.value + 1):
    result, phase_times, query_times, wall_time = RunIteration(
        benchmark_spec, iteration, map_tasks
    )
    bbqpms.append(result.bbqpm)
    validity.append(result.valid)
    iter_md = {
        'iteration': iteration,
        'tpcx_bb_result_valid': result.valid,
        'tpcx_bb_kit_problems': '; '.join(result.problems),
    }
    for metric, value in (
        ('tpcx_bb_t_load', result.t_load),
        ('tpcx_bb_t_ld', result.t_ld),
        ('tpcx_bb_t_pt', result.t_pt),
        ('tpcx_bb_t_t_put', result.t_t_put),
        ('tpcx_bb_t_tt', result.t_tt),
        ('tpcx_bb_driver_wall_time', wall_time),
    ):
      raw_samples.append((metric, value, 'seconds', iter_md))
    raw_samples.append(('tpcx_bb_bbqpm', result.bbqpm, 'BBQpm@SF', iter_md))
    for phase, seconds in phase_times.items():
      raw_samples.append((
          'tpcx_bb_phase_time',
          seconds,
          'seconds',
          dict(iter_md, tpcx_bb_phase=phase),
      ))
    for query in query_times:
      raw_samples.append((
          'tpcx_bb_query_time',
          query.seconds,
          'seconds',
          dict(
              iter_md,
              tpcx_bb_query=query.query,
              tpcx_bb_phase=query.phase,
              tpcx_bb_stream=query.stream,
              tpcx_bb_query_successful=query.successful,
          ),
      ))
    if query_times:
      raw_samples.append((
          'tpcx_bb_failed_queries',
          sum(1 for q in query_times if not q.successful),
          'count',
          iter_md,
      ))
    else:
      logging.warning('No per query times found for TPCx-BB run %d.', iteration)

  all_valid = all(validity)
  if all_valid:
    # Per the specification the reported result is the lower performing run.
    raw_samples.append((
        'tpcx_bb_bbqpm_reported',
        min(bbqpms),
        'BBQpm@SF',
        {'tpcx_bb_result_valid': True},
    ))
  else:
    logging.warning(
        'Not reporting tpcx_bb_bbqpm_reported: the kit declared runs %s '
        'INVALID.',
        [i + 1 for i, valid in enumerate(validity) if not valid],
    )
  reasons = GetNoncomplianceReasons(all_valid)
  metadata.update({
      'tpcx_bb_compliant': not reasons,
      'tpcx_bb_noncompliance_reasons': ','.join(reasons),
  })
  return [
      sample.Sample(metric, value, unit, dict(metadata, **extra))
      for metric, value, unit, extra in raw_samples
  ]


def Cleanup(benchmark_spec):
  """Cleans up the TPCx-BB benchmark.

  All data lives on the cluster (HDFS, the leader's metastore and kit
  directory), which is torn down with the DPB service.

  Args:
    benchmark_spec: The benchmark specification.
  """
  del benchmark_spec  # unused
