"""Executes the TPCx-BB (BigBench) benchmark on an unmanaged Hadoop cluster.

TPCx-BB (TPC Express Benchmark BB, https://www.tpc.org/tpcx-bb/) measures big
data analytics systems with 30 queries (SQL, Java UDF/UDTF, Python streaming,
natural language processing and machine learning) over a retail data model
generated by the kit's PDGF data generator. A benchmark run consists of a load
test, a power test (all queries in one stream) and a throughput test (several
concurrent streams). The primary metric is

  BBQpm@SF = SF * 60 * 30 / (T_LD + sqrt(T_PT * T_TT))

where T_LD = 0.1 * load time, T_PT = 30 * geometric mean of the power test
query times and T_TT = throughput test elapsed time / number of streams.

This benchmark drives the kit's own driver (`bin/bigBench runBenchmark`, as
the kit's TPCxBB_Benchmarkrun.sh does) on the cluster leader with the
`spark_sql` engine of the kit's CDP 7.1 distribution, which runs every query
with `spark-sql --master yarn --deploy-mode client`, and parses the driver's
result block (T_LOAD, T_PT, T_T_PUT, T_TT, BBQpm and the VALID / INVALID
verdict) and the kit's per query times.

Cluster: an unmanaged YARN cluster (unmanaged_dpb_svc_yarn_cluster) provides
HDFS, YARN and MapReduce (used by the data generator). Prepare adds what the
spark_sql engine needs on top of it, see linux_packages/tpcx_bb.py: Spark 3
with Hive support on YARN, a PostgreSQL backed Hive metastore that supports
concurrent sessions, and a YARN configuration (capacity scheduler with fair
ordering, Spark external shuffle service and dynamic allocation) under which
the throughput test streams run concurrently instead of one after the other.
The unmanaged Spark cluster service is not used because it runs Spark
standalone with a Spark build that has no Hive support (no spark-sql CLI).
Managed services (Dataproc, EMR) are not supported yet.

Compliance: samples carry `tpcx_bb_compliant` and
`tpcx_bb_noncompliance_reasons`. Results are never compliant today because
the kit's spark_sql scripts are modified to load the kit's Spark 3.1 machine
learning jar instead of its Spark 2.4 one, and the specification's engine
validation run is not performed (Spark 3 formats some decimals differently
from the kit's reference results, so its strict comparison fails although the
values are equal). Scale factors other than the specification's (1000 and
up), fewer than 2 runs, an HDFS replication below 3 or an INVALID verdict are
also recorded as reasons.

Java: --openjdk_version=8 is required. The kit's PDGF data generator uses
JAXB (javax.xml.bind), which was removed from the JDK in Java 11, and Spark 3.1
does not run on Java 17+.

Capacity: a run at scale factor SF stores about 0.85 GB * SF of generated data
on HDFS, i.e. ~2.5 GB * SF with the HDFS default replication of 3, plus
temporary tables and Spark shuffle data (allow ~50 % more). The default config
(3 workers x 1000 GB) fits the default SF 100. The leader (a worker shaped VM
without data disks) runs the NameNode, ResourceManager, metastore and one
spark-sql driver per stream; their scratch data is on the 100 GB boot disk.

The TPCx-BB kit must be obtained manually; see linux_packages/tpcx_bb.py.
"""

